"""Kaggle kernel: V4FinBench inference arm `boost` (AU5.8 boost, residual pool capped at 100,000), folds (3, 4).

Generated by scripts/kaggle/make_v4_inference_kernels.py; pre-registration in
docs/results/drafts/v4_inference_kernels_2026-11.md. Zero-shot published checkpoint, one inference
setting changed (the embedded CONFIG); no fine-tuning. Pinned to 62a73c3. The checkpoint is the
public kabartay/fintfm-binary file, verified by SHA-256 against runs/v4-cellattn-labels.pt; the
data is V4FinBench's own public Kaggle dataset (Kostrzewa et al., arXiv:2605.10896, CC BY 4.0).
Outputs (per-fold predictions, v4_protocol.json) land in /kaggle/working/boost_f34/. The
reference arm is scored from its saved local predictions, not rerun here.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "62a73c3"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
OUT = "boost_f34"
FOLDS = (3, 4)
CONFIG = """inference:
  feature_chunk: 8
  query_chunk: 512
large_n:
  boost_pool_rows: 100000
  method: boost
"""


def run_arm(root: Path, ckpt: Path, out_dir: Path, folds: tuple[int, ...], device: str,
            max_rows: int | None = None, config: str = CONFIG) -> dict:
    """Score one arm's folds with the embedded configuration.

    Args:
        root: Directory holding ``company_years_h1.parquet``.
        ckpt: The checkpoint file.
        out_dir: Where predictions and ``v4_protocol.json`` are written.
        folds: Folds to score.
        device: ``cuda`` on Kaggle; ``cpu`` only for the local smoke test.
        max_rows: Development cap; ``None`` (the real run) scores the full panel.
        config: YAML text of the arm.

    Returns:
        The ``fintfm.experiments.v4_protocol.run`` record.
    """
    cfg_path = out_dir.with_suffix(".yaml")
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(config)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), out_dir, horizon=0, folds=folds, max_rows=max_rows, root=root,
                 with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device=device, drop_columns=())
    print(summarise(record), flush=True)
    return record


def main() -> None:
    """Find the data, install the pinned fintfm, fetch the checkpoint and score the folds."""
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {hits}")
    root = hits[0].parent
    print(f"data: {root}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{COMMIT}"], check=True)
    import torch
    print(f"torch {torch.__version__}, CUDA available: {torch.cuda.is_available()}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {digest} != {CKPT_SHA256}")
    run_arm(root, ckpt, Path("/kaggle/working") / OUT, FOLDS, "cuda")
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
