"""Write the AU5.1 Kaggle kernel directories: three learning-rate arms, three fold groups each.

Each kernel fine-tunes per dataset (§163's recipe, up to 3,000 steps, early stopping on
inner-validation companies) and scores V4FinBench folds on one Kaggle GPU. An arm's five folds
would not fit one 12 h session at the cap (ESTIMATED 5.5 h per fold at 3,000 steps), so each arm
is three kernels covering folds (0, 1), (2, 3) and (4). The arm's YAML is read from
``configs/arms/au51-<arm>.yaml`` and embedded, as ``task_164_l600`` embeds its own, so the kernel
and the config file cannot drift (``tests/test_au51_arms.py``).

Usage::

    uv run python scripts/kaggle/make_au51_kernels.py --commit <sha of a PUSHED commit that
        contains the early-stopping keys>

Without ``--commit`` the kernels carry the placeholder ``UNPINNED`` and refuse to run.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ARMS = {"lr1e5": "1e-5", "lr3e5": "3e-5", "lr1e4": "1e-4"}
FOLD_GROUPS = {"f01": (0, 1), "f23": (2, 3), "f4": (4,)}
HERE = Path(__file__).resolve().parent
CONFIGS = HERE.parents[1] / "configs" / "arms"
PLACEHOLDER = "UNPINNED"

TEMPLATE = '''"""Kaggle kernel: AU5.1 arm `{arm}` (fine-tuning lr {lr}, up to 3,000 steps, early stopping), folds {folds}.

Generated by scripts/kaggle/make_au51_kernels.py; pre-registration in
docs/results/drafts/au5.1_2026-11.md. Dataset-specific fine-tuning on each fold's training rows,
otherwise as §163; 10% of the training companies are held out as inner validation and the
best-validation-loss weights are kept (never the test fold). Pinned to {commit}. The checkpoint
is the public kabartay/fintfm-binary file, verified by SHA-256 against
runs/v4-cellattn-labels.pt; the data is V4FinBench's own public Kaggle dataset. Outputs
(per-fold predictions, v4_protocol.json with the validation curves) land in
/kaggle/working/{arm}/. Fine-tuning is not pretraining, so there is no --checkpoint-every.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
FOLDS = {folds}
CONFIG = """{config}"""


def main() -> None:
    """Fine-tune per dataset and score this kernel's folds, refusing an unpinned or CPU-only run."""
    if COMMIT == "{placeholder}":
        sys.exit("kernel is not pinned: regenerate with make_au51_kernels.py --commit <pushed sha>")
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {{hits}}")
    root = hits[0].parent
    print(f"data: {{root}}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    import torch
    print(f"torch {{torch.__version__}}, CUDA available: {{torch.cuda.is_available()}}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {{digest}} != {{CKPT_SHA256}}")
    cfg_path = Path("/kaggle/working/{arm}.yaml")
    cfg_path.write_text(CONFIG)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), Path("/kaggle/working/{arm}"), horizon=0, folds=FOLDS,
                 root=root, with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device="cuda")
    print(summarise(record), flush=True)
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
'''


def kernel_dir(arm: str, group: str) -> Path:
    """Directory of one kernel: ``scripts/kaggle/task_au51_<arm>_<group>``."""
    return HERE / f"task_au51_{arm}_{group}"


def render(arm: str, group: str, commit: str) -> tuple[str, dict]:
    """The kernel source and its metadata for one arm and fold group.

    Args:
        arm: Key of :data:`ARMS`.
        group: Key of :data:`FOLD_GROUPS`.
        commit: A pushed commit, or :data:`PLACEHOLDER`.

    Returns:
        ``(kernel source, kernel-metadata dict)``.
    """
    config = (CONFIGS / f"au51-{arm}.yaml").read_text()
    assert '"""' not in config
    slug = f"task_au51_{arm}_{group}"
    src = TEMPLATE.format(arm=f"au51-{arm}-{group}", lr=ARMS[arm], folds=FOLD_GROUPS[group],
                          commit=commit, config=config, placeholder=PLACEHOLDER)
    kid = slug.replace("_", "-")
    meta = {
        "id": f"muhakabartay/fintfm-{kid}", "title": f"fintfm-{kid}", "code_file": f"{slug}.py",
        "language": "python", "kernel_type": "script", "is_private": "true",
        "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "true",
        "dataset_sources": ["sebastiantomczak10/v4-group-corporate-bankruptcy"],
        "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }
    return src, meta


def main() -> None:
    """Write every kernel directory."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--commit", default=PLACEHOLDER)
    args = ap.parse_args()
    for arm in ARMS:
        for group in FOLD_GROUPS:
            src, meta = render(arm, group, args.commit)
            d = kernel_dir(arm, group)
            d.mkdir(exist_ok=True)
            (d / meta["code_file"]).write_text(src)
            (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
            print(d)


if __name__ == "__main__":
    main()
