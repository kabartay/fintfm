"""Generate Kaggle CPU-only kernels for FinTFM's CPU-bound V4FinBench scoring (2026-11-10).

Kaggle's CPU sessions use no GPU or TPU quota, so scoring that runs on this shared Mac's CPU one
fold at a time could run there in parallel, one fold per kernel. **Not used as of 2026-11-10:** the
probe kernel (`scripts/kaggle/cpu_host_probe`) measured a CPU session at 4 cores and about 72 ms per
query row against this Mac's 7 to 8 ms, so a full fold of these jobs would exceed the 12-hour
session limit; kept for a larger host (a TPU session's CPUs, unmeasured). Two job kinds:

* ``pp``: probe plus partitioned contexts (``representation_transfer --partition --stage
  pre_head``), one fold; outputs ``rt.json`` and ``predictions_fold<k>.npz`` with
  ``company_test``, the layout ``runs/local_queue/pp_v4_split.py`` reads.
* ``v4``: ``v4_protocol.run`` with an embedded inference configuration (task 48.24's
  ``maj4000``/``uni4000`` arms), one fold, logistic regression beside it, no boosting.

Every kernel pins fintfm to :data:`COMMIT`, fetches the public published checkpoint and checks its
SHA-256, reads V4FinBench from its public Kaggle dataset, and refuses to start if it finds an
accelerator (a CPU job must not spend GPU or TPU quota). Run from the repository root:

    uv run python scripts/kaggle/make_cpu_kernels.py

then push with ``scripts/kaggle/launch_queue.sh`` (items ``DIR:-``: outputs fetched, nothing
scored locally).
"""

from __future__ import annotations

import json
from pathlib import Path

#: fintfm commit every kernel installs: carries ``representation_transfer --partition`` and the
#: ``company_test`` codes it saves.
COMMIT = "8348c6c"
OWNER = "muhakabartay"
HERE = Path(__file__).parent

#: 48.24's two arms, verbatim from ``runs/local_queue/cfg/4824-*.yaml``.
CONFIGS = {
    "maj4000": "inference:\n  context_positive_floor: 1000000\n  feature_chunk: 8\n"
               "  max_context: 4000\n  query_chunk: 512\n",
    "uni4000": "inference:\n  feature_chunk: 8\n  max_context: 4000\n  query_chunk: 512\n",
}

TEMPLATE = '''"""Kaggle CPU kernel: {title}.

Generated by scripts/kaggle/make_cpu_kernels.py (pinned to {commit}). CPU only, no accelerator:
the kernel exits if it finds a GPU or TPU. Published checkpoint (kabartay/fintfm-binary, SHA-256
checked); V4FinBench from its public Kaggle dataset (CC BY 4.0). Outputs in /kaggle/working/{out}/.
"""

import hashlib
import os
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
KIND = "{kind}"
FOLD = {fold}
OUT = Path("/kaggle/working/{out}")
CONFIG = """{config}"""


def main() -> None:
    """Check there is no accelerator, install fintfm, fetch the checkpoint and score one fold."""
    if Path("/dev/accel0").exists() or os.environ.get("TPU_NAME") or os.environ.get("COLAB_TPU_ADDR"):
        sys.exit("a TPU is attached -- this kernel is CPU only")
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {{hits}}")
    root = hits[0].parent
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    import torch
    if torch.cuda.is_available():
        sys.exit("a GPU is attached -- this kernel is CPU only")
    # Kaggle's default is 2 torch threads on a 4-core session (probe kernel, 2026-11-10)
    torch.set_num_threads(len(os.sched_getaffinity(0)))
    print(f"cpus {{len(os.sched_getaffinity(0))}}, torch {{torch.__version__}}, "
          f"threads {{torch.get_num_threads()}}", flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {{digest}} != {{CKPT_SHA256}}")
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.perf_counter()
    if KIND == "pp":
        from fintfm.experiments.representation_transfer import run
        run(str(ckpt), OUT / "rt.json", folds=(FOLD,), root=root, device="cpu",
            predictions_dir=OUT, stage="pre_head", partition=True)
    else:
        from fintfm.config import load_config
        from fintfm.experiments.v4_protocol import run, summarise
        cfg_path = OUT.with_suffix(".yaml")
        cfg_path.write_text(CONFIG)
        record = run(str(ckpt), OUT, horizon=0, folds=(FOLD,), root=root, with_boosting=False,
                     classical=("logistic_regression",), cfg=load_config(cfg_path), device="cpu")
        print(summarise(record), flush=True)
    print(f"wall {{time.perf_counter() - t0:.0f}} s", flush=True)


if __name__ == "__main__":
    main()
'''


def write_kernel(name: str, title: str, kind: str, fold: int, config: str = "") -> Path:
    """Write one kernel directory under ``scripts/kaggle/``.

    Args:
        name: Directory name, also the kernel slug's suffix.
        title: One-line description for the docstring.
        kind: ``"pp"`` or ``"v4"``.
        fold: The V4FinBench fold the kernel scores.
        config: Inference YAML for ``"v4"`` kernels.

    Returns:
        The kernel directory.
    """
    d = HERE / name
    d.mkdir(exist_ok=True)
    slug = "fintfm-" + name.replace("_", "-")
    (d / f"{name}.py").write_text(TEMPLATE.format(
        title=title, commit=COMMIT, kind=kind, fold=fold, out=name, config=config))
    (d / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{OWNER}/{slug}", "title": slug, "code_file": f"{name}.py", "language": "python",
        "kernel_type": "script", "is_private": "true", "enable_gpu": "false",
        "enable_tpu": "false", "enable_internet": "true",
        "dataset_sources": ["sebastiantomczak10/v4-group-corporate-bankruptcy"],
        "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }, indent=2) + "\n")
    return d


def main() -> None:
    """Write the probe-plus-partition fold kernels and 48.24's per-fold kernels."""
    made = [write_kernel(f"cpu_pp_v4_f{k}", f"probe plus partition, V4FinBench fold {k}", "pp", k)
            for k in (2, 3, 4)]
    made += [write_kernel(f"cpu_4824_{arm}_f{k}", f"48.24 arm {arm}, V4FinBench fold {k}", "v4", k,
                          CONFIGS[arm])
             for arm in CONFIGS for k in range(5)]
    for d in made:
        print(d.name)


if __name__ == "__main__":
    main()
