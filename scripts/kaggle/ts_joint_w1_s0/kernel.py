"""Kaggle kernel: 34.2 joint-objective arm `joint-w1-s0` (classification weight 1.0).

Generated by scripts/kaggle/make_joint_kernels.py; see openspec/changes/joint-objective-training
tasks 34.2. Pretrains configs/arms/joint-w1.yaml (the AU5.9 control recipe, 48,000 tasks,
n_horizons 6) at d58141e on a T4x2 with --checkpoint-every 1000 and
--joint-classification-weight 1.0, then checks the checkpoint records both objectives and
the weight. Outputs in /kaggle/working/joint-w1-s0/: the checkpoint, train.log. V4FinBench scoring is
off Kaggle.
"""

import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "d58141e"
ARM = "joint-w1-s0"
WEIGHT = 1.0
ARM_FLAGS = ['--amp', 'fp16', '--attn-impl', 'split', '--loader', 'stream', '--ddp', '--batch-size', '4', '--seed', '0', '--steps', '6000', '--n-horizons', '6', '--joint-classification-weight', '1.0']
RECIPE_URL = ("https://raw.githubusercontent.com/kabartay/fintfm/" + COMMIT
              + "/configs/arms/joint-w1.yaml")


def main() -> None:
    """Refuse an unpinned or CPU run, install the pinned package, pretrain, check provenance."""
    if COMMIT == "UNPINNED":
        sys.exit("kernel is not pinned: regenerate with make_joint_kernels.py --commit <pushed sha>")
    smi = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                         capture_output=True, text=True, check=False)
    if smi.returncode != 0 or not smi.stdout.strip():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPUs:", smi.stdout.strip(), flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{COMMIT}"], check=True)
    out = Path("/kaggle/working") / ARM
    out.mkdir(parents=True, exist_ok=True)
    recipe = out / "recipe.yaml"
    urllib.request.urlretrieve(RECIPE_URL, recipe)
    ckpt = out / f"{ARM}.pt"
    train = [sys.executable, "-u", "-m", "torch.distributed.run", "--standalone",
             "--nproc-per-node", "2", "-m", "fintfm.modeling.train", "--config", str(recipe),
             "--device", "cuda", "--checkpoint-every", "1000", "--out", str(ckpt), *ARM_FLAGS]
    print("$ " + " ".join(train), flush=True)
    with (out / "train.log").open("w") as log:
        rc = subprocess.run(train, stdout=log, stderr=subprocess.STDOUT, check=False).returncode
    print((out / "train.log").read_text()[-3000:], flush=True)
    if rc != 0:
        sys.exit(f"training failed with exit {rc}")
    from fintfm.provenance import read_checkpoint_provenance
    rec = read_checkpoint_provenance(ckpt) or {}
    print(f"checkpoint: {rec.get('steps_completed')} steps, {rec.get('tasks_seen')} tasks",
          flush=True)
    import torch
    saved = torch.load(ckpt, map_location="cpu", weights_only=False)
    objectives = set(saved.get("trained_objectives", []))
    weight = saved.get("provenance", {}).get("train_config", {}).get(
        "joint_classification_weight")
    print(f"trained_objectives={sorted(objectives)} joint_classification_weight={weight}",
          flush=True)
    for p in out.glob(f"{ARM}.pt.step*"):
        p.unlink()
    if objectives != {"survival", "classification"} or weight != WEIGHT:
        sys.exit(f"the checkpoint does not record the joint objective at weight {WEIGHT}")
    print("done")


if __name__ == "__main__":
    main()
