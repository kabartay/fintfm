def sha256(path: Path) -> str:
    """SHA-256 of a file, read in chunks.

    Args:
        path: The file to hash.

    Returns:
        The lower-case hex digest.
    """
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def find_checkpoint(inputs: Path = Path("/kaggle/input")) -> Path:
    """Locate the arm's checkpoint among the attached kernel outputs and verify its SHA-256.

    Args:
        inputs: Where Kaggle mounts ``kernel_sources``.

    Returns:
        The one matching file.

    Raises:
        SystemExit: When the file is missing, ambiguous, or its hash differs.
    """
    spec = PROBLEM[PROBLEM_TYPE]
    hits = sorted(inputs.rglob(spec["checkpoint_file"]))
    if len(hits) != 1:
        sys.exit(f"expected one {spec['checkpoint_file']} under {inputs}, found {hits}")
    got = sha256(hits[0])
    if got != spec["checkpoint_sha256"]:
        sys.exit(f"{hits[0]}: SHA-256 {got} != pinned {spec['checkpoint_sha256']}; refusing to run")
    print(f"checkpoint {hits[0]} SHA-256 ok", flush=True)
    return hits[0]


def install(fork_root: Path) -> None:
    """Clone the fork at its pin and install it, then fintfm at its pin.

    Args:
        fork_root: Where the fork is cloned.
    """
    pip = [sys.executable, "-m", "pip", "install", "--quiet"]
    url = "https://github.com/kabartay/tabarena.git"
    subprocess.run(
        ["git", "clone", "--quiet", "--branch", FORK_BRANCH, url, str(fork_root)], check=True
    )
    subprocess.run(["git", "-C", str(fork_root), "checkout", "--quiet", FORK_COMMIT], check=True)
    subprocess.run(
        [*pip, f"autogluon.tabular=={AUTOGLUON}", f"autogluon.core[ray]=={AUTOGLUON}"], check=True
    )
    subprocess.run(
        [
            *pip,
            "-e",
            str(fork_root / "packages" / "bencheval"),
            "-e",
            str(fork_root / "packages" / "tabarena"),
        ],
        check=True,
    )
    subprocess.run(
        [*pip, f"fintfm @ git+https://github.com/kabartay/fintfm.git@{FINTFM_COMMIT}"], check=True
    )


def check_fork(fork_root: Path) -> None:
    """Stop unless the fork has the runner and reads every variable this arm sets.

    Args:
        fork_root: The fork's root.

    Raises:
        SystemExit: When the runner or a variable is missing.
    """
    if not (fork_root / "run_fintfm_lite.py").exists():
        sys.exit(f"run_fintfm_lite.py missing at fork commit {FORK_COMMIT}")
    sources = "\n".join(
        p.read_text() for p in (fork_root / "packages/tabarena/src/tabarena").rglob("*.py")
    )
    for var in ("FINTFM_PROBE_CROSSFIT_FOLDS", *LEVER):
        if var not in sources:
            sys.exit(f"{var} is not read anywhere in the fork at commit {FORK_COMMIT}")


def run_env(dataset: str, checkpoint: Path) -> dict[str, str]:
    """The environment of one dataset's process.

    Args:
        dataset: ``FINTFM_DATASETS``.
        checkpoint: The verified checkpoint.

    Returns:
        The inherited environment without ``VIRTUAL_ENV`` and ``FINTFM_*``, plus the arm's settings.
    """
    spec = PROBLEM[PROBLEM_TYPE]
    env = {
        k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV" and not k.startswith("FINTFM_")
    }
    env.update(spec["env"])
    env.update(LEVER)
    env.update(
        {
            "FINTFM_MODEL": "FinTFM-LinProbe",
            "FINTFM_PARAMS": PARAMS,
            "FINTFM_PROBE_CROSSFIT_FOLDS": "0",
            "FINTFM_RUN_NAME": RUN_NAME,
            "FINTFM_DATASETS": dataset,
            spec["checkpoint_env"]: str(checkpoint),
            "FINTFM_DEVICE": "cpu",
            "FINTFM_SKIP_COMPARE": "1",
            "PYTHONUNBUFFERED": "1",
            "OMP_NUM_THREADS": "4",
        }
    )
    return env


def main() -> None:
    """Verify the checkpoint, install, check the fork, fit every dataset, tar, write summary."""
    started = time.time()
    if "<" in RUN_NAME or PROBLEM_TYPE not in PROBLEM:
        sys.exit("template not filled: generate kernels with make_lite_cpu_arms.py")
    checkpoint = find_checkpoint()
    fork_root = Path("/kaggle/tmp/tabarena")
    fork_root.parent.mkdir(parents=True, exist_ok=True)
    install(fork_root)
    check_fork(fork_root)
    head = subprocess.run(
        ["git", "-C", str(fork_root), "rev-parse", "--short=7", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    if head != FORK_COMMIT:
        sys.exit(f"fork HEAD {head} != pinned {FORK_COMMIT}")
    deadline = started + BUDGET_S
    summary = {
        "run": RUN_NAME,
        "problem_type": PROBLEM_TYPE,
        "lever": LEVER,
        "fintfm": FINTFM_COMMIT,
        "fork": FORK_COMMIT,
        "fork_branch": FORK_BRANCH,
        "autogluon": AUTOGLUON,
        "device": "cpu",
        "cpus": os.cpu_count(),
        "datasets": [],
    }
    log_path = WORK / f"{RUN_NAME}.log"
    for ds in PROBLEM[PROBLEM_TYPE]["datasets"]:
        if time.time() > deadline:
            summary["datasets"].append({"dataset": ds, "exit": None, "seconds": 0})
            print(f"{ds}: skipped, session budget spent", flush=True)
            continue
        start = time.time()
        with log_path.open("a") as log:
            log.write(f"=== {time.strftime('%m-%d %H:%M:%S')} dataset {ds}\n")
            log.flush()
            before = log_path.stat().st_size
            try:
                rc = subprocess.run(
                    [sys.executable, "-P", "run_fintfm_lite.py", "--full"],
                    cwd=fork_root,
                    env=run_env(ds, checkpoint),
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    check=False,
                    timeout=DATASET_TIMEOUT_S,
                ).returncode
            except subprocess.TimeoutExpired:
                rc = -1
        with log_path.open() as log:
            log.seek(before)
            hit = "TimeLimitExceeded" in log.read()
        seconds = round(time.time() - start)
        summary["datasets"].append(
            {"dataset": ds, "exit": rc, "seconds": seconds, "time_limit": hit}
        )
        print(f"{ds}: exit {rc}, {seconds} s, time limit hit {hit}", flush=True)
        results = fork_root / "experiments" / RUN_NAME
        if results.exists():
            with tarfile.open(WORK / f"{RUN_NAME}.tar.gz", "w:gz") as tar:
                tar.add(results, arcname=RUN_NAME)
        (WORK / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps([(r["dataset"], r["exit"]) for r in summary["datasets"]]))
    print("done")


if __name__ == "__main__":
    main()
