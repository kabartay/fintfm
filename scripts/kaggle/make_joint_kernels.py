"""Write the 34.2 Kaggle kernel directory: joint survival + classification pretraining.

The kernel pretrains the AU5.9 control recipe (published recipe, 48,000 tasks, ``--n-horizons
6``, hazard period context off) with ``--joint-classification-weight`` set, on a Kaggle T4x2
with the AU5.9 execution flags (fp16, split attention, streamed loader, DDP, batch 4 per GPU),
``--checkpoint-every 1000``. It then reads the checkpoint back and fails unless both
``survival`` and ``classification`` are in ``trained_objectives`` and the weight is recorded.
Scoring on V4FinBench (``fintfm-v4oot``, 34.2's Verify) runs off Kaggle on the returned
checkpoint: a survival checkpoint cannot go through the classification-path harness on Kaggle.

The weight is an OWNER DECISION: the proposal fixes none. ``--weight`` sets it (default 1.0, a
placeholder); the kernel directory name carries it.

Usage::

    uv run python scripts/kaggle/make_joint_kernels.py --commit <sha of a PUSHED commit
        containing configs/arms/joint-w1.yaml> [--weight 1.0]

Without ``--commit`` the kernel carries the placeholder ``UNPINNED`` and refuses to run.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_WEIGHT = 1.0
CONFIG = "joint-w1"
EXEC_FLAGS = [
    "--amp",
    "fp16",
    "--attn-impl",
    "split",
    "--loader",
    "stream",
    "--ddp",
    "--batch-size",
    "4",
    "--seed",
    "0",
    "--steps",
    "6000",
    "--n-horizons",
    "6",
]
HERE = Path(__file__).resolve().parent
PLACEHOLDER = "UNPINNED"

TEMPLATE = '''"""Kaggle kernel: 34.2 joint-objective arm `{arm}` (classification weight {weight}).

Generated by scripts/kaggle/make_joint_kernels.py; see openspec/changes/joint-objective-training
tasks 34.2. Pretrains configs/arms/{config}.yaml (the AU5.9 control recipe, 48,000 tasks,
n_horizons 6) at {commit} on a T4x2 with --checkpoint-every 1000 and
--joint-classification-weight {weight}, then checks the checkpoint records both objectives and
the weight. Outputs in /kaggle/working/{arm}/: the checkpoint, train.log. V4FinBench scoring is
off Kaggle.
"""

import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
ARM = "{arm}"
WEIGHT = {weight!r}
ARM_FLAGS = {flags!r}
RECIPE_URL = ("https://raw.githubusercontent.com/kabartay/fintfm/" + COMMIT
              + "/configs/arms/{config}.yaml")


def main() -> None:
    """Refuse an unpinned or CPU run, install the pinned package, pretrain, check provenance."""
    if COMMIT == "{placeholder}":
        sys.exit("kernel is not pinned: regenerate with make_joint_kernels.py --commit <pushed sha>")
    smi = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                         capture_output=True, text=True, check=False)
    if smi.returncode != 0 or not smi.stdout.strip():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPUs:", smi.stdout.strip(), flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    out = Path("/kaggle/working") / ARM
    out.mkdir(parents=True, exist_ok=True)
    recipe = out / "recipe.yaml"
    urllib.request.urlretrieve(RECIPE_URL, recipe)
    ckpt = out / f"{{ARM}}.pt"
    train = [sys.executable, "-u", "-m", "torch.distributed.run", "--standalone",
             "--nproc-per-node", "2", "-m", "fintfm.modeling.train", "--config", str(recipe),
             "--device", "cuda", "--checkpoint-every", "1000", "--out", str(ckpt), *ARM_FLAGS]
    print("$ " + " ".join(train), flush=True)
    with (out / "train.log").open("w") as log:
        rc = subprocess.run(train, stdout=log, stderr=subprocess.STDOUT, check=False).returncode
    print((out / "train.log").read_text()[-3000:], flush=True)
    if rc != 0:
        sys.exit(f"training failed with exit {{rc}}")
    from fintfm.provenance import read_checkpoint_provenance
    rec = read_checkpoint_provenance(ckpt) or {{}}
    print(f"checkpoint: {{rec.get('steps_completed')}} steps, {{rec.get('tasks_seen')}} tasks",
          flush=True)
    import torch
    saved = torch.load(ckpt, map_location="cpu", weights_only=False)
    objectives = set(saved.get("trained_objectives", []))
    weight = saved.get("provenance", {{}}).get("train_config", {{}}).get(
        "joint_classification_weight")
    print(f"trained_objectives={{sorted(objectives)}} joint_classification_weight={{weight}}",
          flush=True)
    for p in out.glob(f"{{ARM}}.pt.step*"):
        p.unlink()
    if objectives != {{"survival", "classification"}} or weight != WEIGHT:
        sys.exit(f"the checkpoint does not record the joint objective at weight {{WEIGHT}}")
    print("done")


if __name__ == "__main__":
    main()
'''


def arm_name(weight: float) -> str:
    """Arm name for a weight: ``joint-w1-s0`` for 1.0, ``joint-w0p3-s0`` for 0.3."""
    return f"joint-w{str(weight).removesuffix('.0').replace('.', 'p')}-s0"


def render(commit: str, weight: float = DEFAULT_WEIGHT) -> tuple[str, dict]:
    """The kernel source and its metadata.

    Args:
        commit: A pushed commit, or :data:`PLACEHOLDER`.
        weight: The classification-loss weight (OWNER DECISION).

    Returns:
        ``(kernel source, kernel-metadata dict)``.
    """
    arm = arm_name(weight)
    flags = [*EXEC_FLAGS, "--joint-classification-weight", str(weight)]
    src = TEMPLATE.format(
        arm=arm,
        config=CONFIG,
        commit=commit,
        flags=flags,
        weight=weight,
        placeholder=PLACEHOLDER,
    )
    kid = f"ts-{arm}"
    meta = {
        "id": f"muhakabartay/fintfm-{kid}",
        "title": f"fintfm-{kid}",
        "code_file": "kernel.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true",
        "enable_gpu": "true",
        "enable_tpu": "false",
        "enable_internet": "true",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }
    return src, meta


def kernel_dir(weight: float = DEFAULT_WEIGHT) -> Path:
    """Directory of the kernel: ``scripts/kaggle/ts_<arm>``."""
    return HERE / f"ts_{arm_name(weight).replace('-', '_')}"


def main() -> None:
    """Write the kernel directory."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--commit", default=PLACEHOLDER)
    ap.add_argument("--weight", type=float, default=DEFAULT_WEIGHT)
    args = ap.parse_args()
    src, meta = render(args.commit, args.weight)
    d = kernel_dir(args.weight)
    d.mkdir(exist_ok=True)
    (d / "kernel.py").write_text(src)
    (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(d)


if __name__ == "__main__":
    main()
