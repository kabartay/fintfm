"""Kaggle kernel: DR3.11 arm `dr311-ens8-f23` on V4FinBench folds (2, 3), zero-shot, on GPU.

Generated by scripts/kaggle/make_dr311_kernels.py; pre-registration in
docs/results/drafts/dr3.11_2026-11-07.md. §169's partition with one change (the arm's YAML,
embedded below), against runs/dr31/partition. Modelled on task_dr311_ftleaf. Pinned to UNPINNED.
The checkpoint is the public kabartay/fintfm-binary file, verified by SHA-256 against
runs/v4-cellattn-labels.pt; the data is V4FinBench's own public Kaggle dataset. Outputs
(per-fold predictions, v4_protocol.json) land in /kaggle/working/dr311-ens8-f23/.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "UNPINNED"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
FOLDS = (2, 3)
CONFIG = """large_n:
  method: partition
inference:
  n_ensemble: 8
  query_chunk: 512
  feature_chunk: 8
"""


def main() -> None:
    """Score this kernel's folds, refusing an unpinned or CPU-only run."""
    if COMMIT == "UNPINNED":
        sys.exit("kernel is not pinned: regenerate with make_dr311_kernels.py --commit <pushed sha>")
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {hits}")
    root = hits[0].parent
    print(f"data: {root}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{COMMIT}"], check=True)
    import torch
    print(f"torch {torch.__version__}, CUDA available: {torch.cuda.is_available()}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {digest} != {CKPT_SHA256}")
    cfg_path = Path("/kaggle/working/dr311-ens8-f23.yaml")
    cfg_path.write_text(CONFIG)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), Path("/kaggle/working/dr311-ens8-f23"), horizon=0, folds=FOLDS,
                 root=root, with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device="cuda", drop_columns=())
    print(summarise(record), flush=True)
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
