"""Write the DR3.11 Kaggle kernel directories: three partition arms on V4FinBench, by fold group.

Each kernel scores the public checkpoint on some V4FinBench folds with one of the arms
``configs/arms/dr311-{bag4,ens8,bag8}.yaml`` (zero-shot, no fine-tuning; fine-tuning per leaf was
measured null in §208), against §169's partition in ``runs/dr31/partition``. It is modelled on
``task_dr311_ftleaf``. The arm's YAML is embedded with that kernel's two identity-preserving chunk
settings merged in, so the kernel and the config file cannot drift (``tests/test_dr311_arms.py``).

Fold groups put folds 2 and 3 first (``f23``), so the first kernel of an arm is the futility
check of ``docs/results/drafts/dr3.11_2026-11-07.md``; the other folds follow only if it passes.
A group is sized to fit one 12 h session (ESTIMATED GPU time in that draft).

Usage::

    uv run python scripts/kaggle/make_dr311_kernels.py --commit <sha of a PUSHED commit>

Without ``--commit`` the kernels carry the placeholder ``UNPINNED`` and refuse to run.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

#: Fold groups per arm. bag4 costs about 4 times a one-member partition fold, ens8 and bag8 about 8.
ARM_GROUPS = {
    "bag4": {"f23": (2, 3), "f014": (0, 1, 4)},
    "ens8": {"f23": (2, 3), "f01": (0, 1), "f4": (4,)},
    "bag8": {"f23": (2, 3), "f01": (0, 1), "f4": (4,)},
}
HERE = Path(__file__).resolve().parent
CONFIGS = HERE.parents[1] / "configs" / "arms"
PLACEHOLDER = "UNPINNED"
#: Merged into the arm's ``inference`` section in the kernel. Identity-preserving (tests); a
#: 2,048 chunk did not fit a T4 in task_dr311_ftleaf.
CHUNKS = {"query_chunk": 512, "feature_chunk": 8}

TEMPLATE = '''"""Kaggle kernel: DR3.11 arm `{arm}` on V4FinBench folds {folds}, zero-shot, on GPU.

Generated by scripts/kaggle/make_dr311_kernels.py; pre-registration in
docs/results/drafts/dr3.11_2026-11-07.md. §169's partition with one change (the arm's YAML,
embedded below), against runs/dr31/partition. Modelled on task_dr311_ftleaf. Pinned to {commit}.
The checkpoint is the public kabartay/fintfm-binary file, verified by SHA-256 against
runs/v4-cellattn-labels.pt; the data is V4FinBench's own public Kaggle dataset. Outputs
(per-fold predictions, v4_protocol.json) land in /kaggle/working/{arm}/.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
FOLDS = {folds}
CONFIG = """{config}"""


def main() -> None:
    """Score this kernel's folds, refusing an unpinned or CPU-only run."""
    if COMMIT == "{placeholder}":
        sys.exit("kernel is not pinned: regenerate with make_dr311_kernels.py --commit <pushed sha>")
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {{hits}}")
    root = hits[0].parent
    print(f"data: {{root}}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    import torch
    print(f"torch {{torch.__version__}}, CUDA available: {{torch.cuda.is_available()}}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {{digest}} != {{CKPT_SHA256}}")
    cfg_path = Path("/kaggle/working/{arm}.yaml")
    cfg_path.write_text(CONFIG)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), Path("/kaggle/working/{arm}"), horizon=0, folds=FOLDS,
                 root=root, with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device="cuda", drop_columns=())
    print(summarise(record), flush=True)
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
'''


def kernel_dir(arm: str, group: str) -> Path:
    """Directory of one kernel: ``scripts/kaggle/task_dr311_<arm>_<group>``."""
    return HERE / f"task_dr311_{arm}_{group}"


def config_text(arm: str) -> str:
    """The arm's YAML as embedded in its kernels: the config file with :data:`CHUNKS` merged in.

    Args:
        arm: Key of :data:`ARM_GROUPS`.

    Returns:
        YAML text whose parsed form is the arm file's plus the two chunk settings.
    """
    cfg = yaml.safe_load((CONFIGS / f"dr311-{arm}.yaml").read_text())
    cfg.setdefault("inference", {}).update(CHUNKS)
    return yaml.safe_dump(cfg, sort_keys=False)


def render(arm: str, group: str, commit: str) -> tuple[str, dict]:
    """The kernel source and its metadata for one arm and fold group.

    Args:
        arm: Key of :data:`ARM_GROUPS`.
        group: Key of ``ARM_GROUPS[arm]``.
        commit: A pushed commit, or :data:`PLACEHOLDER`.

    Returns:
        ``(kernel source, kernel-metadata dict)``.
    """
    slug = f"task_dr311_{arm}_{group}"
    src = TEMPLATE.format(arm=f"dr311-{arm}-{group}", folds=ARM_GROUPS[arm][group],
                          commit=commit, config=config_text(arm), placeholder=PLACEHOLDER)
    kid = slug.replace("_", "-")
    meta = {
        "id": f"muhakabartay/fintfm-{kid}", "title": f"fintfm-{kid}", "code_file": f"{slug}.py",
        "language": "python", "kernel_type": "script", "is_private": "true",
        "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "true",
        "dataset_sources": ["sebastiantomczak10/v4-group-corporate-bankruptcy"],
        "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }
    return src, meta


def main() -> None:
    """Write every kernel directory."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--commit", default=PLACEHOLDER)
    args = ap.parse_args()
    for arm, groups in ARM_GROUPS.items():
        for group in groups:
            src, meta = render(arm, group, args.commit)
            d = kernel_dir(arm, group)
            d.mkdir(exist_ok=True)
            (d / meta["code_file"]).write_text(src)
            (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
            print(d)


if __name__ == "__main__":
    main()
