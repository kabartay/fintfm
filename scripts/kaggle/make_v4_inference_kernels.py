"""Write the V4FinBench inference-arm Kaggle kernels (AU5.12, AU4.2, AU4.3, AU5.8).

Each kernel scores the public ``kabartay/fintfm-binary`` checkpoint on V4FinBench horizon 0 with
one inference setting changed, on one Kaggle GPU, for a group of folds. The reference arms
(§196's ``ens8``, the one-member default, §163's fine-tuned arm) already exist locally for all
five folds, so the kernels run the arm only; scoring is local (``scripts/compare_v4_scores.py``).
The arm YAML is read from ``configs/arms/`` and embedded, with a small kernel overlay
(:data:`OVERLAY`) that only sets memory-chunk knobs. Pre-registration:
``docs/results/drafts/v4_inference_kernels_2026-11.md``.

Usage::

    uv run python scripts/kaggle/make_v4_inference_kernels.py [--commit <pushed sha>]

The default pin is 62a73c3, a commit on origin/main that carries every setting used here.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
CONFIGS = HERE.parents[1] / "configs" / "arms"
DEFAULT_COMMIT = "62a73c3"

#: arm -> (config file under configs/arms, label). Folds per group are in :data:`GROUPS`.
ARMS: dict[str, tuple[str, str]] = {
    "tfsq8": ("au512-ens8-tfsq.yaml", "AU5.12 ens8 with transforms rank, squash"),
    "ctx900e3": ("proxy/au43-ctx900-ens3.yaml", "AU4.3 max_context 900, 3 members"),
    "au42proto": ("au42-prototype.yaml", "AU4.2 prototype undersampling"),
    "pc16": ("au58-retrieval-pc16.yaml", "AU5.8 per-class retrieval, 16 positives"),
    "boost": ("au58-boost.yaml", "AU5.8 boost, residual pool capped at 100,000"),
}
#: arm -> {group name: folds}. 8-member arms are split so each kernel fits one 12 h session.
GROUPS: dict[str, dict[str, tuple[int, ...]]] = {
    "tfsq8": {"f01": (0, 1), "f23": (2, 3), "f4": (4,)},
    "ctx900e3": {"f01234": (0, 1, 2, 3, 4)},
    "au42proto": {"f01234": (0, 1, 2, 3, 4)},
    "pc16": {"f01234": (0, 1, 2, 3, 4)},
    # boost's cost is unmeasured: time fold 0 first, then (1, 2) and (3, 4) only if it fits
    "boost": {"f0": (0,), "f12": (1, 2), "f34": (3, 4)},
}
#: Applied over every arm. A 2,048-row query chunk did not fit a T4 after fine-tuning
#: (task_dr311_ftleaf); 512 / 8 are the chunk sizes it used. Both are identity-preserving knobs
#: (``tests/``: chunking does not change the output), so no arm's setting is altered.
OVERLAY = {"inference": {"query_chunk": 512, "feature_chunk": 8}}

TEMPLATE = '''"""Kaggle kernel: V4FinBench inference arm `{arm}` ({label}), folds {folds}.

Generated by scripts/kaggle/make_v4_inference_kernels.py; pre-registration in
docs/results/drafts/v4_inference_kernels_2026-11.md. Zero-shot published checkpoint, one inference
setting changed (the embedded CONFIG); no fine-tuning. Pinned to {commit}. The checkpoint is the
public kabartay/fintfm-binary file, verified by SHA-256 against runs/v4-cellattn-labels.pt; the
data is V4FinBench's own public Kaggle dataset (Kostrzewa et al., arXiv:2605.10896, CC BY 4.0).
Outputs (per-fold predictions, v4_protocol.json) land in /kaggle/working/{arm}_{group}/. The
reference arm is scored from its saved local predictions, not rerun here.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
OUT = "{arm}_{group}"
FOLDS = {folds}
CONFIG = """{config}"""


def run_arm(root: Path, ckpt: Path, out_dir: Path, folds: tuple[int, ...], device: str,
            max_rows: int | None = None, config: str = CONFIG) -> dict:
    """Score one arm's folds with the embedded configuration.

    Args:
        root: Directory holding ``company_years_h1.parquet``.
        ckpt: The checkpoint file.
        out_dir: Where predictions and ``v4_protocol.json`` are written.
        folds: Folds to score.
        device: ``cuda`` on Kaggle; ``cpu`` only for the local smoke test.
        max_rows: Development cap; ``None`` (the real run) scores the full panel.
        config: YAML text of the arm.

    Returns:
        The ``fintfm.experiments.v4_protocol.run`` record.
    """
    cfg_path = out_dir.with_suffix(".yaml")
    cfg_path.parent.mkdir(parents=True, exist_ok=True)
    cfg_path.write_text(config)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), out_dir, horizon=0, folds=folds, max_rows=max_rows, root=root,
                 with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device=device, drop_columns=())
    print(summarise(record), flush=True)
    return record


def main() -> None:
    """Find the data, install the pinned fintfm, fetch the checkpoint and score the folds."""
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {{hits}}")
    root = hits[0].parent
    print(f"data: {{root}}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    import torch
    print(f"torch {{torch.__version__}}, CUDA available: {{torch.cuda.is_available()}}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {{digest}} != {{CKPT_SHA256}}")
    run_arm(root, ckpt, Path("/kaggle/working") / OUT, FOLDS, "cuda")
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
'''


def arm_config(arm: str) -> str:
    """The arm's YAML with :data:`OVERLAY` merged in, as the text a kernel embeds.

    Args:
        arm: Key of :data:`ARMS`.

    Returns:
        YAML text (comments of the source file are dropped; the keys are not).
    """
    cfg = yaml.safe_load((CONFIGS / ARMS[arm][0]).read_text())
    for section, keys in OVERLAY.items():
        cfg.setdefault(section, {}).update(keys)
    text = yaml.safe_dump(cfg, sort_keys=True)
    assert '"""' not in text
    return text


def kernel_dir(arm: str, group: str) -> Path:
    """Directory of one kernel: ``scripts/kaggle/task_v4inf_<arm>_<group>``."""
    return HERE / f"task_v4inf_{arm}_{group}"


def render(arm: str, group: str, commit: str) -> tuple[str, dict]:
    """The kernel source and its metadata for one arm and fold group.

    Args:
        arm: Key of :data:`ARMS`.
        group: Key of ``GROUPS[arm]``.
        commit: A pushed commit.

    Returns:
        ``(kernel source, kernel-metadata dict)``.
    """
    slug = f"task_v4inf_{arm}_{group}"
    src = TEMPLATE.format(arm=arm, group=group, label=ARMS[arm][1], folds=GROUPS[arm][group],
                          commit=commit, config=arm_config(arm))
    kid = slug.replace("_", "-")
    meta = {
        "id": f"muhakabartay/fintfm-{kid}", "title": f"fintfm-{kid}", "code_file": f"{slug}.py",
        "language": "python", "kernel_type": "script", "is_private": "true",
        "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "true",
        "dataset_sources": ["sebastiantomczak10/v4-group-corporate-bankruptcy"],
        "competition_sources": [], "kernel_sources": [], "model_sources": [],
    }
    return src, meta


def main() -> None:
    """Write every kernel directory."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--commit", default=DEFAULT_COMMIT)
    args = ap.parse_args()
    for arm, groups in GROUPS.items():
        for group in groups:
            src, meta = render(arm, group, args.commit)
            d = kernel_dir(arm, group)
            d.mkdir(exist_ok=True)
            (d / meta["code_file"]).write_text(src)
            (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
            print(d)


if __name__ == "__main__":
    main()
