"""Write the AU5.9 Kaggle kernel directories: the flag-on arm and its flag-off control.

Each kernel pretrains the published recipe at 48,000 tasks with ``--n-horizons 6`` (the arm adds
``--hazard-period-context``), on a Kaggle T4x2 with the AU5.3 kernel's execution flags
(fp16, split attention, streamed loader, DDP, batch 4 per GPU), then runs the AU5.9 Verify
(``fintfm.experiments.hazard_period_probe``) on the checkpoint. A survival checkpoint cannot be
scored by the classification path (``assert_trained_for``), so there is no V4FinBench scoring in
the kernel; V4FinBench's term-structure harness runs off Kaggle on the returned checkpoint.

Usage::

    uv run python scripts/kaggle/make_au59_kernels.py --commit <sha of a PUSHED commit that
        contains configs/arms/au59-*.yaml and fintfm/experiments/hazard_period_probe.py>

Without ``--commit`` the kernels carry the placeholder ``UNPINNED`` and refuse to run.
Pre-registration: docs/results/drafts/au5.9_2026-11.md.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ARMS = {
    "ctx": ("au59-hazard-ctx-s0", "au59-hazard-period-context", ["--hazard-period-context"]),
    "ctrl": ("au59-hazard-ctrl-s0", "au59-hazard-ctrl", []),
}
EXEC_FLAGS = ["--amp", "fp16", "--attn-impl", "split", "--loader", "stream", "--ddp",
              "--batch-size", "4", "--seed", "0", "--steps", "6000", "--n-horizons", "6"]
HERE = Path(__file__).resolve().parent
PLACEHOLDER = "UNPINNED"

TEMPLATE = '''"""Kaggle kernel: AU5.9 arm `{arm}`, then the hazard-period Verify.

Generated by scripts/kaggle/make_au59_kernels.py; pre-registration in
docs/results/drafts/au5.9_2026-11.md. Pretrains configs/arms/{config}.yaml (the published recipe,
48,000 tasks, n_horizons 6{flag_note}) at {commit} on a T4x2 with --checkpoint-every 1000, then
scores the checkpoint on the synthetic Verify with and without context periods. Outputs in
/kaggle/working/{arm}/: the checkpoint, train.log, probe/*.json.
"""

import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "{commit}"
ARM = "{arm}"
ARM_FLAGS = {flags!r}
RECIPE_URL = ("https://raw.githubusercontent.com/kabartay/fintfm/" + COMMIT
              + "/configs/arms/{config}.yaml")


def main() -> None:
    """Refuse an unpinned or CPU run, install the pinned package, pretrain, then probe."""
    if COMMIT == "{placeholder}":
        sys.exit("kernel is not pinned: regenerate with make_au59_kernels.py --commit <pushed sha>")
    smi = subprocess.run(["nvidia-smi", "--query-gpu=name", "--format=csv,noheader"],
                         capture_output=True, text=True, check=False)
    if smi.returncode != 0 or not smi.stdout.strip():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPUs:", smi.stdout.strip(), flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{{COMMIT}}"], check=True)
    out = Path("/kaggle/working") / ARM
    out.mkdir(parents=True, exist_ok=True)
    recipe = out / "recipe.yaml"
    urllib.request.urlretrieve(RECIPE_URL, recipe)
    ckpt = out / f"{{ARM}}.pt"
    train = [sys.executable, "-u", "-m", "torch.distributed.run", "--standalone",
             "--nproc-per-node", "2", "-m", "fintfm.modeling.train", "--config", str(recipe),
             "--device", "cuda", "--checkpoint-every", "1000", "--out", str(ckpt), *ARM_FLAGS]
    print("$ " + " ".join(train), flush=True)
    with (out / "train.log").open("w") as log:
        rc = subprocess.run(train, stdout=log, stderr=subprocess.STDOUT, check=False).returncode
    print((out / "train.log").read_text()[-3000:], flush=True)
    if rc != 0:
        sys.exit(f"training failed with exit {{rc}}")
    from fintfm.provenance import read_checkpoint_provenance
    rec = read_checkpoint_provenance(ckpt) or {{}}
    print(f"checkpoint: {{rec.get('steps_completed')}} steps, {{rec.get('tasks_seen')}} tasks",
          flush=True)
    probe = [sys.executable, "-u", "-m", "fintfm.experiments.hazard_period_probe",
             "--model", str(ckpt), "--n-horizons", "6", "--n-tasks", "200",
             "--device", "cuda", "--out", str(out / "probe")]
    print("$ " + " ".join(probe), flush=True)
    rc = subprocess.run(probe, check=False).returncode
    for p in out.glob(f"{{ARM}}.pt.step*"):
        p.unlink()
    if rc != 0:
        sys.exit(f"the Verify failed with exit {{rc}}; the checkpoint is in {{out}}")
    print("done")


if __name__ == "__main__":
    main()
'''


def render(key: str, commit: str) -> tuple[str, dict]:
    """The kernel source and its metadata for one arm.

    Args:
        key: Key of :data:`ARMS`.
        commit: A pushed commit, or :data:`PLACEHOLDER`.

    Returns:
        ``(kernel source, kernel-metadata dict)``.
    """
    arm, config, extra = ARMS[key]
    slug = f"ts_{arm.replace('-', '_')}"
    flags = [*EXEC_FLAGS, *extra]
    src = TEMPLATE.format(arm=arm, config=config, commit=commit, flags=flags,
                          flag_note=", hazard_period_context on" if extra else
                          ", hazard_period_context off", placeholder=PLACEHOLDER)
    kid = slug.replace("_", "-")
    meta = {
        "id": f"muhakabartay/fintfm-{kid}", "title": f"fintfm-{kid}", "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": "true",
        "enable_gpu": "true", "enable_tpu": "false", "enable_internet": "true",
        "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        "model_sources": [],
    }
    return src, meta


def kernel_dir(key: str) -> Path:
    """Directory of one kernel: ``scripts/kaggle/ts_<arm>``."""
    return HERE / f"ts_{ARMS[key][0].replace('-', '_')}"


def main() -> None:
    """Write both kernel directories."""
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--commit", default=PLACEHOLDER)
    args = ap.parse_args()
    for key in ARMS:
        src, meta = render(key, args.commit)
        d = kernel_dir(key)
        d.mkdir(exist_ok=True)
        (d / "kernel.py").write_text(src)
        (d / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
        print(d)


if __name__ == "__main__":
    main()
