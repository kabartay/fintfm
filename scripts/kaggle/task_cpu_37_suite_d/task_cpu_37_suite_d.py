def sha256(path: Path) -> str:
    """SHA-256 of a file, read in chunks.

    Args:
        path: The file to hash.

    Returns:
        The lower-case hex digest.
    """
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def fetch_verified(url: str, dest: Path, expected: str) -> None:
    """Download ``url`` to ``dest`` and stop unless its SHA-256 is ``expected``.

    Args:
        url: Public source.
        dest: Local path (parents are created).
        expected: Pinned SHA-256.

    Raises:
        SystemExit: When the digest differs; the file is removed first.
    """
    dest.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(url, dest)
    got = sha256(dest)
    if got != expected:
        dest.unlink()
        sys.exit(f"{url}: SHA-256 {got} != pinned {expected}; refusing to run")
    print(f"{dest.name} SHA-256 ok", flush=True)


def suite_command(dataset: str, out: Path = OUT) -> list[str]:
    """The ``suite_scoring`` command of one dataset (defaults of the openspec note, 4 threads).

    Args:
        dataset: A cleared key such as ``clf_num/Higgs``.
        out: Output directory of the per-dataset JSON.

    Returns:
        The argument vector, run from ``WS``.
    """
    return [
        sys.executable, "-P", "-m", "fintfm.experiments.suite_scoring",
        "--checkpoint", CKPT_ARG,
        "--datasets", dataset,
        "--out", str(out),
        "--threads", str(THREADS),
    ]  # fmt: skip


def run_env() -> dict[str, str]:
    """Environment of one dataset's process: the inherited one with the thread counts set."""
    env = {k: v for k, v in os.environ.items() if k != "VIRTUAL_ENV"}
    env.update({"OMP_NUM_THREADS": str(THREADS), "MKL_NUM_THREADS": str(THREADS),
                "PYTHONUNBUFFERED": "1"})  # fmt: skip
    return env


def main() -> None:
    """Verify inputs, install the pinned fintfm, score each dataset in a subprocess, write summary."""
    started = time.time()
    if "<" in PART or not DATASETS:
        sys.exit("template not filled: generate kernels with make_cpu_37_kernels.py")
    unknown = set(DATASETS) - set(CSV_SHA256)
    if unknown:
        sys.exit(f"not cleared datasets: {sorted(unknown)}")
    WS.mkdir(parents=True, exist_ok=True)
    (WORK / "logs").mkdir(exist_ok=True)
    fetch_verified(CKPT_URL, WS / "runs" / "v4-cellattn-labels.pt", CKPT_SHA256)
    for key in DATASETS:
        fetch_verified(
            f"{HF_BASE}/{key}.csv", WS / "data" / "cache" / "tabular_benchmark" / f"{key}.csv",
            CSV_SHA256[key],
        )  # fmt: skip
    package = f"fintfm[bench] @ git+https://github.com/kabartay/fintfm.git@{FINTFM_COMMIT}"
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet", package], check=True)
    deadline = started + BUDGET_S
    summary = {
        "part": PART, "fintfm": FINTFM_COMMIT, "checkpoint_sha256": CKPT_SHA256,
        "hf_dataset_revision": HF_DATASET_REVISION, "threads": THREADS,
        "cpus": os.cpu_count(), "datasets": [],
    }  # fmt: skip
    for ds in DATASETS:
        if time.time() > deadline:
            summary["datasets"].append({"dataset": ds, "exit": None, "seconds": 0})
            print(f"{ds}: skipped, session budget spent", flush=True)
            continue
        start = time.time()
        log_path = WORK / "logs" / (ds.replace("/", "__") + ".log")
        with log_path.open("a") as log:
            try:
                rc = subprocess.run(
                    suite_command(ds), cwd=WS, env=run_env(), stdout=log,
                    stderr=subprocess.STDOUT, check=False, timeout=DATASET_TIMEOUT_S,
                ).returncode  # fmt: skip
            except subprocess.TimeoutExpired:
                rc = -1
        seconds = round(time.time() - start)
        summary["datasets"].append({"dataset": ds, "exit": rc, "seconds": seconds})
        print(f"{ds}: exit {rc}, {seconds} s", flush=True)
        (WORK / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps([(r["dataset"], r["exit"]) for r in summary["datasets"]]))
    print("done")


if __name__ == "__main__":
    main()
