"""Kaggle kernel: AU5.1 arm `au51-lr1e4-f4` (fine-tuning lr 1e-4, up to 3,000 steps, early stopping), folds (4,).

Generated by scripts/kaggle/make_au51_kernels.py; pre-registration in
docs/results/drafts/au5.1_2026-11.md. Dataset-specific fine-tuning on each fold's training rows,
otherwise as §163; 10% of the training companies are held out as inner validation and the
best-validation-loss weights are kept (never the test fold). Pinned to 62a73c3. The checkpoint
is the public kabartay/fintfm-binary file, verified by SHA-256 against
runs/v4-cellattn-labels.pt; the data is V4FinBench's own public Kaggle dataset. Outputs
(per-fold predictions, v4_protocol.json with the validation curves) land in
/kaggle/working/au51-lr1e4-f4/. Fine-tuning is not pretraining, so there is no --checkpoint-every.
"""

import hashlib
import subprocess
import sys
import urllib.request
from pathlib import Path

COMMIT = "62a73c3"
CKPT_URL = "https://huggingface.co/kabartay/fintfm-binary/resolve/f116bfd43a2b15c65ed3551ea8c38e3364629ddc/v4-cellattn-labels.pt"
CKPT_SHA256 = "d231b062483c9261aae4c503ad5359db295fc7206fa0183f51763e4953c518d2"
FOLDS = (4,)
CONFIG = """# AU5.1: fine-tuning at published scale, learning rate 1e-4. Up to 3,000 steps, stopped early on
# inner-validation companies (10% of the fold's training companies, held out of every fine-tuning
# task; never the fold's test rows or the protocol's validation split). Everything else is
# §163's setting. Pre-registration: docs/results/drafts/au5.1_2026-11.md. NOT PRODUCTION.
inference:
  finetune_steps: 3000
  finetune_lr: 1.0e-4
  finetune_batch: 2
  finetune_query: 512
  finetune_val_frac: 0.1
  finetune_eval_every: 10
  finetune_patience: 16
  finetune_val_tasks: 4
  finetune_val_query: 1024
  finetune_val_pos_frac: 0.1
  query_chunk: 512        # identity-preserving (tests); a 2,048 chunk did not fit a T4 after fine-tuning
  feature_chunk: 8        # identity-preserving (tests)
"""


def main():
    if COMMIT == "UNPINNED":
        sys.exit("kernel is not pinned: regenerate with make_au51_kernels.py --commit <pushed sha>")
    hits = sorted(Path("/kaggle/input").rglob("company_years_h1.parquet"))
    if len(hits) != 1:
        sys.exit(f"expected one company_years_h1.parquet under /kaggle/input, found {hits}")
    root = hits[0].parent
    print(f"data: {root}", flush=True)
    subprocess.run([sys.executable, "-m", "pip", "install", "--quiet",
                    f"fintfm @ git+https://github.com/kabartay/fintfm.git@{COMMIT}"], check=True)
    import torch
    print(f"torch {torch.__version__}, CUDA available: {torch.cuda.is_available()}", flush=True)
    if not torch.cuda.is_available():
        sys.exit("no GPU in this session (quota exhausted?) -- refusing a CPU run")
    print("GPU:", torch.cuda.get_device_name(0), flush=True)
    ckpt = Path("/kaggle/working/v4-cellattn-labels.pt")
    urllib.request.urlretrieve(CKPT_URL, ckpt)
    digest = hashlib.sha256(ckpt.read_bytes()).hexdigest()
    if digest != CKPT_SHA256:
        sys.exit(f"checkpoint hash {digest} != {CKPT_SHA256}")
    cfg_path = Path("/kaggle/working/au51-lr1e4-f4.yaml")
    cfg_path.write_text(CONFIG)
    from fintfm.config import load_config
    from fintfm.experiments.v4_protocol import run, summarise
    record = run(str(ckpt), Path("/kaggle/working/au51-lr1e4-f4"), horizon=0, folds=FOLDS,
                 root=root, with_boosting=False, classical=("logistic_regression",),
                 cfg=load_config(cfg_path), device="cuda")
    print(summarise(record), flush=True)
    ckpt.unlink()  # the public file; no need to ship it back
    print("done")


if __name__ == "__main__":
    main()
