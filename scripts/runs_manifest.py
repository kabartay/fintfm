"""Write ``runs/MANIFEST.json``: the checkpoints ``docs/results/FINDINGS.md`` cites, by hash.

Why this exists
---------------
Trained weights never enter git (``CLAUDE.md``), so a finding that names
``runs/v4-cellattn-labels.pt`` names a file only one machine holds, and nothing records which
bytes it meant. A path can be overwritten by a later run of the same name and every finding
citing it would then silently point at different weights. The manifest is the committed half:
for every checkpoint FINDINGS cites that exists locally, its path, size, SHA-256 and the
sections that cite it (design review DR1.2). It is regenerated by hand, never by a test, and
only the JSON is committed; ``runs/`` stays ignored.

A citation is any token ending in ``.pt``: ``runs/<path>.pt`` is looked up at that path under
the runs directory, and a bare ``name.pt`` (or ``/tmp/name.pt``) at the top of the runs
directory and, failing that, anywhere under it by file name. Citations that resolve to no
local file are listed under ``missing`` rather than dropped, so the manifest also says which
cited weights this machine cannot vouch for.

Usage::

    uv run python scripts/runs_manifest.py --runs-dir /path/to/main/checkout/runs
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

#: A cited checkpoint: a path-like token ending in ``.pt``, not followed by more of a name
#: (``x.pt.state`` and ``x.pt.step500`` are training state and partial saves, not checkpoints).
_CITATION = re.compile(r"[\w./+-]+\.pt(?!\w)(?!\.\w)")

#: A level-2 heading; its number, if it has one, becomes the section label ``§N``.
_SECTION = re.compile(r"^## (?:§)?(\d+)\b|^## (.+)$")


def cited_checkpoints(findings: str) -> dict[str, list[str]]:
    """Every ``.pt`` token in a FINDINGS text and the sections citing it.

    Args:
        findings: The text of ``docs/results/FINDINGS.md``.

    Returns:
        ``{token: [section, ...]}``, sections in document order without repeats. A section is
        ``"§N"`` for a numbered level-2 heading, the heading text for an unnumbered one, and
        ``"preamble"`` before the first.
    """
    cited: dict[str, list[str]] = defaultdict(list)
    for section, line in _lines_by_section(findings):
        for token in _CITATION.findall(line):
            if section not in cited[token]:
                cited[token].append(section)
    return dict(cited)


def _lines_by_section(findings: str) -> list[tuple[str, str]]:
    """Every non-heading line of a FINDINGS text with the label of the section holding it.

    Args:
        findings: The text of ``docs/results/FINDINGS.md``.

    Returns:
        ``(section, line)`` pairs in document order; see :func:`cited_checkpoints`.
    """
    section, out = "preamble", []
    for line in findings.splitlines():
        m = _SECTION.match(line)
        if m:
            section = f"§{m.group(1)}" if m.group(1) else m.group(2).strip()
        else:
            out.append((section, line))
    return out


def _sha256(path: Path) -> str:
    """SHA-256 of a file, read in 1 MiB chunks."""
    digest = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def resolve(token: str, runs_dir: Path, by_name: dict[str, list[Path]]) -> list[Path]:
    """The local files a citation can mean.

    Args:
        token: A cited ``.pt`` token.
        runs_dir: The runs directory.
        by_name: Every ``.pt`` file under ``runs_dir``, keyed by file name.

    Returns:
        ``runs_dir/<path after runs/>`` when the token names one, else ``runs_dir/<name>``,
        else every file of that name under ``runs_dir``; empty when none exists.
    """
    rel = token.split("runs/", 1)[1] if "runs/" in token else Path(token).name
    direct = runs_dir / rel
    if direct.is_file():
        return [direct]
    if "runs/" in token:
        return []
    return sorted(by_name.get(Path(token).name, []))


def build_manifest(findings_path: Path, runs_dir: Path) -> dict:
    """Build the manifest for one FINDINGS file against one runs directory.

    Args:
        findings_path: ``docs/results/FINDINGS.md``.
        runs_dir: Directory holding the checkpoints; read only.

    Returns:
        ``{"findings_sha256", "checkpoints", "missing"}``. Each checkpoint has ``path``
        (``runs/``-relative), ``size`` in bytes, ``sha256``, ``cited_as`` and ``sections``;
        each missing entry has ``cited_as`` and ``sections``. Both lists are sorted by path or
        token, so regenerating against unchanged files gives an identical file.
    """
    text = findings_path.read_text()
    by_name: dict[str, list[Path]] = defaultdict(list)
    for dirpath, _dirs, files in os.walk(runs_dir):
        for f in files:
            if f.endswith(".pt"):
                by_name[f].append(Path(dirpath) / f)
    found: dict[Path, dict] = {}
    missing = []
    for token, sections in sorted(cited_checkpoints(text).items()):
        paths = resolve(token, runs_dir, by_name)
        if not paths:
            missing.append({"cited_as": token, "sections": sections})
        for path in paths:
            entry = found.setdefault(path, {"cited_as": [], "sections": []})
            entry["cited_as"].append(token)
            entry["sections"] += [s for s in sections if s not in entry["sections"]]
    order = {s: i for i, (s, _) in reversed(list(enumerate(_lines_by_section(text))))}
    for entry in found.values():  # two citations of one file: keep document order
        entry["sections"].sort(key=order.__getitem__)
    checkpoints = [
        {
            "path": f"runs/{path.relative_to(runs_dir).as_posix()}",
            "size": path.stat().st_size,
            "sha256": _sha256(path),
            **entry,
        }
        for path, entry in sorted(found.items())
    ]
    return {
        "findings_sha256": hashlib.sha256(text.encode()).hexdigest(),
        "checkpoints": checkpoints,
        "missing": missing,
    }


def main(argv: list[str] | None = None) -> None:
    """Write the manifest.

    Args:
        argv: Command-line arguments; ``sys.argv`` when ``None``.
    """
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--findings", type=Path, default=REPO / "docs" / "results" / "FINDINGS.md")
    p.add_argument("--runs-dir", type=Path, default=REPO / "runs",
                   help="where the checkpoints are; read only")
    p.add_argument("--out", type=Path, default=REPO / "runs" / "MANIFEST.json")
    args = p.parse_args(argv)
    manifest = build_manifest(args.findings, args.runs_dir.resolve())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print(f"{len(manifest['checkpoints'])} cited checkpoints found, "
          f"{len(manifest['missing'])} cited but absent; wrote {args.out}")


if __name__ == "__main__":
    main()
